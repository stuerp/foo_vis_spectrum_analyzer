/// <summary>
/// Gets an initialized audio chunk.
/// </summary>
bool GetAudioChunk(audio_chunk & chunk, uint32_t sampleRate, uint32_t frameCount) noexcept
{
    assert(!fb2k::is_main_thread());

    const uint32_t ChannelCount = 1;

    audio_sample * Samples = new audio_sample[frameCount * ChannelCount];

    if (Samples == nullptr)
        return false;

    // Generate samples using a window function.
    for (uint32_t i = 0; i < frameCount; ++i)
    {
    /** Hann
        const double x = (double) i / (double) (frameCount - 1);

        Samples[i] = 0.5 * (1. + (audio_sample) std::cos(x * std::numbers::pi));
    **/
    /** Hamming
        const double x = 2. * std::numbers::pi * (double) i / (double) (frameCount - 1);

        Samples[i] = 0.54 - 0.46 * (audio_sample) std::cos(x);
    **/
    /** Bartlett
        Samples[i] = 1. - (double) i / (double) (frameCount - 1);
     **/
        constexpr double Frequency = 2'300.0;

        constexpr double Pi    = std::numbers::pi;
        constexpr double TwoPi = 2. * Pi;

        const double t = (double) i / (double) sampleRate;

        Samples[i] = (audio_sample) std::sin(TwoPi * Frequency * t);
    }
 
    chunk = audio_chunk_impl(Samples, frameCount, ChannelCount, sampleRate);
    
    delete[] Samples;
    
    return true;
}

/// <summary>
/// Draws some debug information.
/// </summary>
void uielement_t::RenderDebug() noexcept
{
    RECT rc;

    ::GetClientRect(m_hWnd, &rc);

    const D2D1_RECT_F Rect = { (FLOAT) rc.right / 2.f, (FLOAT) rc.top, (FLOAT) rc.right, (FLOAT) rc.bottom };

    ComPtr<IDWriteTextFormat> TextFormat;

    const FLOAT FontSize = PointsToDIPs(12.f); // In DIPs

    HRESULT hr = DirectWrite::CreateTextFormat(L"Segoe UI", FontSize, DWRITE_TEXT_ALIGNMENT_TRAILING, DWRITE_PARAGRAPH_ALIGNMENT_NEAR, TextFormat.GetAddressOf());

    if (FAILED(hr))
        return;

    std::wstring Text = msc::FormatText(L"%.2fs", _RenderState._PlaybackTime);

    _D2DDeviceContext->DrawText(Text.c_str(), (UINT) Text.size(), TextFormat.Get(), Rect, _DebugBrush.Get(), D2D1_DRAW_TEXT_OPTIONS_NONE);
}

